"""CEFR word lists for the ``cefr_overshoot`` guard.

File format (YAML)::

    source: "where the list comes from and its licence"
    reviewed_by: "name"            # PLACEHOLDER until a person approves it
    levels:
      A1: [a, an, apple, ...]
      A2: [...]

Levels are cumulative: a word listed at A1 is also allowed at A2 and above. The shipped list is
generated by ``scripts/build_wordlist.py`` from the CEFR-J and Octanove profiles; without a file
the guard only checks sentence length.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import get_args

import yaml

from english_tutor.models import CefrLevel

LEVELS: tuple[CefrLevel, ...] = get_args(CefrLevel)
MAX_UNKNOWN_SHARE = 0.15  # flag a sentence when more of its words are outside the list
DEFAULT_PATH = Path(__file__).resolve().parent.parent / "data" / "cefr_wordlist.yaml"

_WORD_RE = re.compile(r"[A-Za-z]+(?:'[A-Za-z]+)?")
_SUFFIXES = ("'s", "iest", "ier", "ies", "ied", "ing", "est", "es", "ed", "er", "s", "d")
_Y_SUFFIXES = frozenset({"iest", "ier", "ies", "ied"})  # happier -> happy, cried -> cry


@dataclass(frozen=True)
class CefrWordlist:
    source: str
    reviewed_by: str
    allowed: dict[CefrLevel, frozenset[str]]  # cumulative per level

    def knows(self, word: str, level: CefrLevel) -> bool:
        """True when ``word`` or a simple base form of it is allowed at ``level``."""
        allowed = self.allowed[level]
        word = word.lower()
        if word in allowed:
            return True
        for suffix in _SUFFIXES:
            if word.endswith(suffix) and len(word) > len(suffix) + 1:
                stem = word[: -len(suffix)]
                candidates = {stem, stem + "e"}
                if suffix in _Y_SUFFIXES:
                    candidates.add(stem + "y")
                if len(stem) > 2 and stem[-1] == stem[-2]:  # stopped -> stop, bigger -> big
                    candidates.add(stem[:-1])
                if candidates & allowed:
                    return True
        return False

    def unknown_share(
        self, sentence: str, level: CefrLevel, exempt: frozenset[str] = frozenset()
    ) -> float:
        """Share of words above ``level`` + 1, ignoring proper nouns and exempt words."""
        check_level = LEVELS[min(LEVELS.index(level) + 1, len(LEVELS) - 1)]
        words = _WORD_RE.findall(sentence)
        counted = unknown = 0
        for i, word in enumerate(words):
            name = word[0].isupper() and (i > 0 or not self.knows(word, LEVELS[-1]))
            if name or word.lower() in exempt:
                continue  # proper nouns (a sentence-initial one when no word) and target words
            counted += 1
            if not self.knows(word, check_level):
                unknown += 1
        return unknown / counted if counted else 0.0


def load_wordlist(path: Path = DEFAULT_PATH) -> CefrWordlist | None:
    """Parse a word list file; ``None`` when the file does not exist."""
    if not path.exists():
        return None
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    levels = raw.get("levels") or {}
    unknown_levels = set(levels) - set(LEVELS)
    if unknown_levels:
        raise ValueError(f"{path}: unknown CEFR levels {sorted(unknown_levels)}")
    allowed: dict[CefrLevel, frozenset[str]] = {}
    seen: set[str] = set()
    for level in LEVELS:
        seen |= {str(w).strip().lower() for w in levels.get(level) or []}
        allowed[level] = frozenset(seen)
    return CefrWordlist(
        source=str(raw.get("source", "")),
        reviewed_by=str(raw.get("reviewed_by", "PLACEHOLDER")),
        allowed=allowed,
    )
